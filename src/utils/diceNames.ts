export function getDiceCallName(d1: number, d2: number): string {
  if (d1 === d2) {
    return DOUBLE_NAMES[d1] || `${DIE_NAMES[d1]} دوبل`;
  }
  const key = `${Math.max(d1, d2)}-${Math.min(d1, d2)}`;
  if (SPECIAL_NAMES[key]) {
    return SPECIAL_NAMES[key];
  }
  return `${DIE_NAMES[Math.max(d1, d2)]} ${DIE_NAMES[Math.min(d1, d2)]}`;
}

export function getDiceSingleName(d: number): string {
  return DIE_NAMES[d] || `${d}`;
}

/**
 * دلال ودلع مصري خاص للبفة والكلام الحلو
 */
export function getSweetVoicePhrase(d1: number, d2: number): string {
  // لو بفة (رقمين زي بعض)
  if (d1 === d2) {
    const list = BAFFAH_SWEET_TALK[d1];
    if (list && list.length > 0) {
      const phrase = list[Math.floor(Math.random() * list.length)];
      return phrase;
    }
    return `بَفّة يا سكر! يا سيدي يا سيدي على الحلاوة!`;
  }

  // رميات مميزة
  const key = `${Math.max(d1, d2)}-${Math.min(d1, d2)}`;
  if (SPECIAL_SWEET_TALK[key]) {
    const list = SPECIAL_SWEET_TALK[key];
    return list[Math.floor(Math.random() * list.length)];
  }

  // رميات عادية مع دلع خفيف
  const baseName = getDiceCallName(d1, d2);
  const sweetEndings = [
    'يا عسل',
    'يا قمر',
    'يا جميل',
    'يا سكر',
    'يا حليوة',
    'يا رايق',
  ];
  const ending = sweetEndings[Math.floor(Math.random() * sweetEndings.length)];
  return `${baseName} ${ending}!`;
}

